import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const cat = JSON.parse(fs.readFileSync(path.join(root, 'catalogue/catalogue.json'), 'utf8'));
const routes = cat.routes.filter(r => !r.staffOnly && r.group !== 'staff' && r.group !== 'maintenance');
const skipped = cat.routes.length - routes.length;
const table = Object.fromEntries(routes.map(r => [r.operationId, [r.method, r.path, r.auth, r.params.map(p => [p.name, !!p.optional])]]));
const head = `const SCOPES = ${JSON.stringify(cat.scopes)};\nconst ROUTES = ${JSON.stringify(table)};\n`;
const core = fs.readFileSync(path.join(root, 'src/core.mjs'), 'utf8').replace('__VERSION__', pkg.version).replace(/^\/\/ The hand-written[^\n]*\n/, '');

fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist/index.mjs'), head + core);
const names = ['APIError', 'ScopeError', 'TransportError', 'Client', 'startAppLinkLogin', 'shown_name', 'scope_mask', 'scope_names', 'has_scope', 'SCOPES', 'ROUTES', 'VERSION'];
const cjs = (head + core).replace(/^export \{[^\n]*\n/m, '').replace(/^export (class|const|async function) /gm, '$1 ') + `module.exports = { ${names.join(', ')} };\n`;
fs.writeFileSync(path.join(root, 'dist/index.cjs'), cjs);

const esc = s => String(s || '').replace(/\*\//g, '* /').replace(/\s+/g, ' ').trim();
const key = n => (/^[A-Za-z_$][\w$]*$/.test(n) ? n : JSON.stringify(n));
const method = r => {
  const req = r.params.filter(p => !p.optional).length > 0;
  const fields = r.params.map(p => `${key(p.name)}${p.optional ? '?' : ''}: string | number`);
  const doc = `${r.method} ${r.path}.${r.surface ? ` [${r.surface}]` : ''} ${esc(r.notes)}`.slice(0, 500);
  return `  /** ${doc} */\n  ${r.operationId}(args${req ? '' : '?'}: CallArgs${fields.length ? ` & { ${fields.join('; ')} }` : ''}): Promise<any>;`;
};
const dts = `// Generated by scripts/build.mjs. Method names match the Python SDK. [website], [drive], [forums], [devices] in a comment mean the server refuses other tokens.
export interface CallArgs {
  query?: Record<string, unknown>;
  json?: unknown;
  data?: Record<string, unknown>;
  /** a Blob or File, or [filename, bytes, mimeType] */
  files?: Record<string, Blob | [string, Uint8Array, string?]>;
  raw?: boolean;
}
export interface ClientOptions { baseUrl?: string; authScheme?: 'Bearer' | 'Bot'; timeout?: number; allowInsecure?: boolean; origin?: string | null; fetch?: typeof fetch }
export class APIError extends Error { status: number; payload: unknown; error: string; required_scope: number | null; disabled_by_admin: boolean; moved_to: string | null; reason: string | null; retry_after: number | null }
export class ScopeError extends APIError { scope: string | null }
export class TransportError extends Error {}
export const SCOPES: Record<string, number>;
export const ROUTES: Record<string, [string, string, string, [string, boolean][]]>;
export const VERSION: string;
export interface AppLinkLogin { appId: string; link: string; code: string; state: string; url: string; matches(link: string): boolean; finish(link: string | null, opts?: { grant?: string }): Promise<{ token: string; scopes: number }> }
/** Start a desktop App's sign-in through its app link (PKCE). Open .url, then .finish(the link your app was opened with). */
export function startAppLinkLogin(appId: string, link: string, opts?: { baseUrl?: string; allowInsecure?: boolean; fetch?: typeof fetch }): Promise<AppLinkLogin>;
/** display_name when they have one, else username */
export function shown_name(user: { username?: string; display_name?: string | null } | null | undefined): string;
export function scope_mask(...names: string[]): number;
export function scope_names(mask: number): string[];
export function has_scope(mask: number, name: string): boolean;
export class Client {
  constructor(token?: string | null, options?: ClientOptions);
  baseUrl: string;
  request(method: string, path: string, options?: CallArgs & { auth?: boolean }): Promise<any>;
  call(operationId: string, args?: CallArgs & Record<string, unknown>): Promise<any>;
  product(productId: string): Promise<any>;
  products_of(username: string): Promise<any>;
  add_to_cart(productId: string, options?: { plan?: string; quantity?: number }): Promise<any>;
  add_payment_to_cart(to: string, amount: number, options?: { note?: string }): Promise<any>;
  product_access(productId: string): Promise<any>;
  quote_directly(items: unknown[]): Promise<any>;
  pay_directly(items: unknown[], expectedTotal: number, options?: { idempotency_key?: string }): Promise<any>;
  /** set your display name (1-32 characters; null or '' clears it) */
  set_display_name(name: string | null): Promise<{ success: boolean; display_name?: string | null }>;
  clear_display_name(): Promise<{ success: boolean; display_name?: string | null }>;
  /** your own display name, or null */
  display_name(): Promise<string | null>;
${routes.map(method).join('\n')}
}
`;
fs.writeFileSync(path.join(root, 'dist/index.d.ts'), dts);
fs.writeFileSync(path.join(root, 'dist/index.d.cts'), dts);
console.log(`${routes.length} routes (${skipped} staff routes left out), version ${pkg.version}`);
